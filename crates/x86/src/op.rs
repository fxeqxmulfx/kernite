macro_rules! ops {
    ($($name:ident = $text:literal,)*) => {
        /// The instructions kernels use, by mnemonic.
        #[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
        pub enum Op {
            $(
                #[doc = concat!("`", $text, "`")]
                $name,
            )*
        }

        impl Op {
            /// The name the assembler knows it by.
            pub fn mnemonic(self) -> &'static str {
                match self {
                    $(Op::$name => $text,)*
                }
            }
        }
    };
}

